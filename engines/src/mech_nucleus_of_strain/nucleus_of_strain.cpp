static std::string g_platform = "cpu";

void set_platform(const std::string& platform)
{
    if (platform != "cpu" && platform != "gpu")
        throw std::invalid_argument("platform must be 'cpu' or 'gpu'");
#ifndef USE_CUDA
    if (platform == "gpu")
        throw std::runtime_error("GPU not available: not compiled with USE_CUDA");
#endif
    g_platform = platform;
}

std::string get_platform()
{
    return g_platform;
}

std::map<std::string, std::vector<double>>
compute_geomech(
    std::vector<double>& coordinates, 
    std::vector<double>& prisms, 
    std::vector<double>& pressure,
    double poisson,
    double young,
    std::vector<double>& temperature,
    double thermal_expansion)
{
    /*
    Displacement and stress components produced by pore - pressure variations in
    right - rectangular prisms.

    Parameters
    ----------
    coordinates : 2d - array
    2d numpy array containing ``y``, ``x`` and ``z`` Cartesian cordinates
    of the computation points.All coordinates should be in meters.
    prisms : 2d - array
    2d array containing the Cartesian coordinates of the prism(s).Each
    line contains the coordinates of a prism in following order : y1, y2,
    x1, x2, z2 and z1.All coordinates should be in meters.
    pressure : 1d array
    1d array containing the pressure of each prism in MPa.
    poisson : float
    Poisson's ratio.
    young : float
    Young's modulus in MPa.

    Returns
    ------ -
    result : array
    x - component of the displacement field generated by the prisms at the
    computation points.
    */
    //dtype = "float64",
    //disable_checks = True
 
/*
// Sanity checks
if (!disable_checks) {
    if (pressure.size() != prisms.shape[0])
        cout << "Number of elements in pressure " << pressure.size() <<
        "mismatch the number of prisms" << prisms.shape[0] << endl;
        )
        _check_prisms(prisms)
}*/


int n_eval_points = static_cast<int>(coordinates.size() / 3);

std::map<std::string, std::vector<double>> result;

std::vector<double> ux_p, uy_p, uz_p;
ux_p.resize(n_eval_points);
uy_p.resize(n_eval_points);
uz_p.resize(n_eval_points);

std::vector<double> ux_t, uy_t, uz_t;
ux_t.resize(n_eval_points);
uy_t.resize(n_eval_points);
uz_t.resize(n_eval_points);

double mult_p = -Cm(poisson, young) / (4 * M_PI);
double mult_t = -thermal_expansion * (1 + poisson) / (1 - poisson) / (4 * M_PI);
double poisson_coeff = (3 - 4 * poisson);

//Iterate over computation points
#pragma omp parallel for
for (int i = 0; i < n_eval_points; i++)
{
    std::array<double, 3> coords;
    coords[0] = coordinates[3 * i + 0];
    coords[1] = coordinates[3 * i + 1];
    coords[2] = coordinates[3 * i + 2];

    // compute kernels for displacements at one point
    auto point_res = compute_point(coords, prisms, pressure, temperature, poisson_coeff);

    ux_p[i] = point_res[0] * mult_p;
    uy_p[i] = point_res[1] * mult_p;
    uz_p[i] = point_res[2] * mult_p;

    ux_t[i] = point_res[3] * mult_t;
    uy_t[i] = point_res[4] * mult_t;
    uz_t[i] = point_res[5] * mult_t;
}

result["ux_p"] = ux_p;
result["uy_p"] = uy_p;
result["uz_p"] = uz_p;

result["ux_t"] = ux_t;
result["uy_t"] = uy_t;
result["uz_t"] = uz_t;

return result;
}


std::array<double, 6>
compute_point(std::array<double, 3>& coordinates, std::vector<double>& prisms, std::vector<double>& pressure, 
    std::vector<double>& temperature, double poisson_coeff)
{
    /*
    Compute the displacement or stress component at the computations points

    Parameters
    ----------
    coordinates : 1d array
    1d array containing ``y``, ``x`` and ``z`` Cartesian coordinates of the
    computation points(in meters).
    prisms : 2d - array
    2d array containing the Cartesian coordinates of the prism(s).Each
    line contains the coordinates of a prism in following order : y1, y2,
    x1, x2, z2 and z1.All coordinates should be in meters.
    pressure : 1d array
    1d array containing the pressure of each prism in MPa.
    kernel : func
    Kernel function to be used for computing the desired field component.
    out : 1d - array
    Array where the resulting field component values will be stored.
    Must have the same size as the arrays contained on ``coordinates``.
    */
    int n_prisms = static_cast<int>(prisms.size() / 6);

    if (pressure.size() != static_cast<size_t>(n_prisms))
    {
        std::cout << "Error! Inconsistent input array sizes! pressure " << pressure.size() << " prisms " << n_prisms << "\n";
        exit(1);
    }

    double ux_p = 0;
    double uy_p = 0;
    double uz_p = 0;
    double ux_t = 0;
    double uy_t = 0;
    double uz_t = 0;

    // Iterate over the prism boundaries to compute the result of the
    // integration(see Nagy et al., 2000)
    //#pragma omp parallel for reduction(+: ux_p, uy_p, uz_p, ux_t, uy_t, uz_t)
    for (int m = 0; m < n_prisms; m++) {
        auto prism = &prisms[6*m]; // current prism
        double c_z = 0.5 * (prism[4] + prism[5]);

        // Accumulate signed kernel sums for this prism, then multiply by
        // pressure/temperature once (instead of 8 times inside the ijk loop)
        double sum_krn_x = 0, sum_krn_y = 0, sum_krn_z = 0;

        for (int i = 0; i < 2; i++) {
            for (int j = 0; j < 2; j++) {
                for (int k = 0; k < 2; k++) {
                    auto y_prism = prism[1 - i];
                    auto x_prism = prism[3 - j];
                    auto z_prism = prism[5 - k];

                    // compute kernels
                    auto krnls = kernel_displs(y_prism, x_prism, z_prism, c_z,
                        coordinates[0], coordinates[1], coordinates[2]);

                    // d_x1 + (3 - 4 * poisson) * d_x2 + d_xz2;
                    double krn_x = krnls[0] + poisson_coeff * krnls[1] + krnls[2];
                    double krn_y = krnls[3] + poisson_coeff * krnls[4] + krnls[5];
                    double krn_z = krnls[6] - poisson_coeff * krnls[7] + krnls[8];

                    // If i, j or k is 1, the shift_ * will refer to the
                    // lower boundary, meaning the corresponding term should
                    // have a minus sign
                    double pow_ = pow_1(i, j, k);
                    sum_krn_x += pow_ * krn_x;
                    sum_krn_y += pow_ * krn_y;
                    sum_krn_z += pow_ * krn_z;
                }//k
            }//j
        }//i

        ux_p += pressure[m]    * sum_krn_x;
        uy_p += pressure[m]    * sum_krn_y;
        uz_p += pressure[m]    * sum_krn_z;
        ux_t += temperature[m] * sum_krn_x;
        uy_t += temperature[m] * sum_krn_y;
        uz_t += temperature[m] * sum_krn_z;
    }//for (m)

    std::array<double, 6> out;
    out[0] = ux_p;
    out[1] = uy_p;
    out[2] = uz_p;

    out[3] = ux_t;
    out[4] = uy_t;
    out[5] = uz_t;

    return out;
}


// Kernels for x - component of displacement in the infinite space domain
std::array<double, 9>
kernel_displs(double y, double x, double z, double zc, double yp, double xp, double zp)
{
    double Y  = yp - y;
    double X  = xp - x;
    double Z  = zp - z;
    double Z2 = Z + 2 * zc;

    // Reuse Y^2+X^2 for both rho computations
    double YX2  = Y * Y + X * X;
    double rho  = sqrt(YX2 + Z  * Z);
    double rho2 = sqrt(YX2 + Z2 * Z2);

    // Precompute 6 unique log terms (original code recomputes 12)
    double logYrho   = safe_log(Y  + rho);
    double logZrho   = safe_log(Z  + rho);
    double logXrho   = safe_log(X  + rho);
    double logYrho2  = safe_log(Y  + rho2);
    double logZ2rho2 = safe_log(Z2 + rho2);
    double logXrho2  = safe_log(X  + rho2);

    // Shared atan term reused by z2 (out[7]) and zz2 (out[8])
    double atan_z2 = safe_atan2(X * Y, Z2 * rho2);

    std::array<double, 9> out;
    out[0] = Y * logZrho   + Z  * logYrho   - X  * safe_atan2(Y * Z,  X  * rho);   // x1
    out[1] = Y * logZ2rho2 + Z2 * logYrho2  - X  * safe_atan2(Y * Z2, X  * rho2);  // x2
    out[3] = X * logZrho   + Z  * logXrho   - Y  * safe_atan2(X * Z,  Y  * rho);   // y1
    out[4] = X * logZ2rho2 + Z2 * logXrho2  - Y  * safe_atan2(X * Z2, Y  * rho2);  // y2
    out[6] = X * logYrho   + Y  * logXrho   - Z  * safe_atan2(X * Y,  Z  * rho);   // z1
    out[7] = X * logYrho2  + Y  * logXrho2  - Z2 * atan_z2;                         // z2
    out[2] = 2 * zp * logYrho2;                                                      // xz2
    out[5] = 2 * zp * logXrho2;                                                      // yz2
    out[8] = -2 * zp * atan_z2;                                                      // zz2

    return out;
}
